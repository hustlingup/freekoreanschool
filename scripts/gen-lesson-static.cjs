/* ── Block assembly ──────────────────────────────────────────────────────── */
function buildBlock(lang, lessons, opts = {}) {
  const t = L[lang];
  const totalSteps = lessons.reduce((n, l) => n + l.data.steps.length, 0);
  const totalStages = opts.isVocab
    ? lessons.length
    : lessons.reduce((n, l) => n + (l.data.stages ? l.data.stages.length : 1), 0);

  const intro = fill(opts.isVocab ? t.vocabIntro : t.intro, {
    steps: totalSteps, stages: totalStages,
  });

  const body = lessons.map((l, idx) => {
    if (opts.isVocab) {
      // one <section> per category, numbered as a topic
      return renderLesson(l.data, lang, t, {
        stageWord: t.topic,
        headingPrefix: `${esc(t.topic)} ${idx + 1}`,
      });
    }
    return renderLesson(l.data, lang, t);
  }).join('\n');

  // vocabulary-browser.html has no StepRunner, so it cannot collapse the block
  // via js/step-runner.js. Ship the same progressive-enhancement behaviour
  // inline: open by default (and for no-JS visitors), collapsed once the
  // interactive picker above has actually rendered.
  const selfCollapse = opts.selfCollapse ? SELF_COLLAPSE : '';

  return [
    START,
    STYLE,
    '<details id="lesson-static" class="lesson-static" open>',
    `<summary>${esc(t.ref)}</summary>`,
    `<p class="ls-intro">${esc(intro)}</p>`,
    body,
    '</details>',
    selfCollapse,
    END,
  ].filter(Boolean).join('\n');
}

/* ── HTML splicing ───────────────────────────────────────────────────────── */

/** Index just past the matching </div> for the element opening at `open`. */
function endOfDiv(html, open) {
  const re = /<\/?div\b[^>]*>/gi;
  re.lastIndex = open;
  let depth = 0, m;
  while ((m = re.exec(html))) {
    if (m[0][1] === '/') {
      depth--;
      if (depth === 0) return m.index + m[0].length;
    } else if (!/\/>$/.test(m[0])) {
      depth++;
    }
  }
  return -1;
}

function splice(html, block, anchorAttr) {
  const s = html.indexOf(START);
  if (s !== -1) {
    const e = html.indexOf(END, s);
    if (e === -1) throw new Error('lesson-static:start without matching end');
    return html.slice(0, s) + block + html.slice(e + END.length);
  }
  const open = html.indexOf(anchorAttr);
  if (open === -1) return null;
  const divStart = html.lastIndexOf('<div', open);
  const after = endOfDiv(html, divStart);
  if (after === -1) return null;
  return html.slice(0, after) + '\n\n' + block + '\n' + html.slice(after);
}

