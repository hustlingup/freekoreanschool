/* ── HTML helpers ────────────────────────────────────────────────────────── */
function esc(s) {
  if (s == null) return '';
  return String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
/** Korean text, marked up for screen readers, search engines and font stacks. */
function ko(s) {
  if (s == null || s === '') return '';
  return `<span lang="ko">${esc(s)}</span>`;
}
function fill(tpl, vars) {
  return tpl.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
}

