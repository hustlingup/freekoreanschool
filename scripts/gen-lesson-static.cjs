/* Types that are practice repeats of the immediately preceding step and carry
   no unique prose — rendered by nothing, but "handled" so they never trip the
   unhandled-type warning, and transparent to run-batching so the demos they sit
   between still group into one table. (stroke_trace re-practices its stroke_demo.) */
const TRANSPARENT = new Set(['stroke_trace']);

const unhandled = new Set();

/** Render one lesson JSON as <section>s, one per stage. */
function renderLesson(data, lang, t, opts = {}) {
  const out = [];
  const stages = data.stages || [{ id: 1, name: '', first_step: 1 }];
  const stageWord = opts.stageWord || t.stage;

  // Group steps by stage id (steps without a stage fall into the first).
  const byStage = new Map();
  for (const s of data.steps) {
    const id = s.stage !== undefined ? s.stage : stages[0].id;
    if (!byStage.has(id)) byStage.set(id, []);
    byStage.get(id).push(s);
  }

  for (const stage of stages) {
    const steps = byStage.get(stage.id) || [];
    if (!steps.length) continue;
    const name = loc(stage, 'name', lang) || stage.name;
    const heading = opts.headingPrefix
      ? `${opts.headingPrefix}${name ? ' — ' : ''}${esc(name)}`
      : `${esc(stageWord)} ${stage.id}${name ? ' · ' + esc(name) : ''}`;
    out.push('<section class="ls-stage">');
    out.push(`<h2 class="ls-h2">${heading}${stage.name_kr ? ` <span class="ls-kr">${ko(stage.name_kr)}</span>` : ''}</h2>`);

    // Walk the stage, batching contiguous runs of the same grouped type.
    let i = 0;
    while (i < steps.length) {
      const type = steps[i].type;
      if (TRANSPARENT.has(type)) {
        // Handled: emits nothing, produces no duplicate content.
        i++;
      } else if (GROUPED[type]) {
        // Collect the run of this grouped type, stepping over any transparent
        // steps interleaved between them (e.g. stroke_trace between stroke_demo)
        // so the whole run still becomes one table.
        const run = [steps[i]];
        let j = i + 1;
        while (j < steps.length && (steps[j].type === type || TRANSPARENT.has(steps[j].type))) {
          if (steps[j].type === type) run.push(steps[j]);
          j++;
        }
        out.push(GROUPED[type](run, lang, t));
        i = j;
      } else if (type === 'reading_card') {
        out.push(renderReadingCard(steps[i], lang, t));
        i++;
      } else if (type === 'lesson_complete') {
        out.push(renderComplete(steps[i], lang, t));
        i++;
      } else {
        unhandled.add(type);
        i++;
      }
    }
    out.push('</section>');
  }
  return out.join('\n');
}

